//! Catching signals for the supervisor: a handler that only records which
//! signals arrived and wakes the event loop through a pipe (the "self-pipe
//! trick", TLPI §63.5.2). All real work happens later, in the loop.
//!
//! A signal handler can interrupt the program anywhere, including inside the
//! memory allocator. So the handler, like the child after `fork`, may only use
//! async-signal-safe operations: atomics, `write`, and saving/restoring errno.
//! The lints below turn the likely panics into compile errors.

#![deny(
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects,
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic
)]

use std::os::fd::{BorrowedFd, RawFd};
use std::sync::atomic::{AtomicBool, AtomicI32, AtomicU8, Ordering};

use libc::c_int;
use nix::errno::Errno;

use super::signal::MAX_SIGNAL;
use crate::{Error, Result};

/// One slot per signal number (index 0 is unused).
#[allow(
    clippy::cast_sign_loss,
    clippy::arithmetic_side_effects,
    reason = "a positive constant, checked at compile time"
)]
const SLOTS: usize = MAX_SIGNAL as usize + 1;
/// Per signal: the [`Sources`] bits of every delivery since the last drain.
/// Zero means "not pending".
static PENDING: [AtomicU8; SLOTS] = [const { AtomicU8::new(0) }; SLOTS];
/// The wake pipe. Created once per process and never closed: a handler
/// running during teardown could otherwise write into a reused descriptor.
static WAKE_READ: AtomicI32 = AtomicI32::new(-1);
static WAKE_WRITE: AtomicI32 = AtomicI32::new(-1);
/// The supervised child, so a signal it sends us can be told apart.
static CHILD_PID: AtomicI32 = AtomicI32::new(0);
/// Only one set of handlers per process.
static ACTIVE: AtomicBool = AtomicBool::new(false);

/// Whether shipyard forwards `signal` to the command.
///
/// Not forwarded: SIGCHLD (it's how shipyard learns about the command);
/// signals about shipyard's own faults or limits (SEGV, BUS, FPE, ILL, ABRT,
/// SYS, TRAP, EMT, XCPU, XFSZ); SIGPIPE (Rust ignores it) and SIGURG (socket
/// noise); SIGKILL and SIGSTOP (can't be caught); and the job-control signals
/// TSTP, TTIN, TTOU and CONT. The shell stops and resumes shipyard and the
/// command together; CONT is caught only to notice that shipyard was resumed
/// (see `Signals::install`).
pub(crate) fn is_forwardable(signal: c_int) -> bool {
    let never = [
        libc::SIGKILL,
        libc::SIGSTOP,
        libc::SIGCHLD,
        libc::SIGSEGV,
        libc::SIGBUS,
        libc::SIGFPE,
        libc::SIGILL,
        libc::SIGABRT,
        libc::SIGSYS,
        libc::SIGTRAP,
        libc::SIGXCPU,
        libc::SIGXFSZ,
        libc::SIGPIPE,
        libc::SIGURG,
        libc::SIGTSTP,
        libc::SIGTTIN,
        libc::SIGTTOU,
        libc::SIGCONT,
        #[cfg(not(target_os = "linux"))]
        libc::SIGEMT,
    ];
    (1..=MAX_SIGNAL).contains(&signal) && !never.contains(&signal)
}

/// Where deliveries of one signal came from, as far as the kernel says.
///
/// Signals coalesce: if one arrives twice before the loop looks, both
/// deliveries' sources are recorded together.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub(crate) struct Sources(u8);

impl Sources {
    /// Generated by the kernel, including by the terminal (Ctrl-C, window
    /// size, hangup). Only Linux reports this: on macOS a terminal signal
    /// looks exactly like a `kill` from the process that wrote to the
    /// terminal, so it shows up as [`Sources::OTHER`].
    pub(crate) const KERNEL: Self = Self(1);
    /// Sent by the supervised command itself.
    pub(crate) const COMMAND: Self = Self(2);
    /// Sent by any other process, or by a sender the kernel didn't name.
    pub(crate) const OTHER: Self = Self(4);

    pub(crate) fn contains(self, other: Self) -> bool {
        self.0 & other.0 == other.0
    }

    #[cfg(test)]
    pub(crate) fn union(self, other: Self) -> Self {
        Self(self.0 | other.0)
    }
}

/// A signal that arrived, and from where.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Arrival {
    pub(crate) signal: c_int,
    pub(crate) sources: Sources,
}

/// Signals caught even if they were ignored at startup, because shipyard
/// needs them itself and never forwards them: SIGCHLD (an inherited "ignore"
/// would make the kernel throw away the command's exit status), SIGCONT (to
/// notice being resumed) and SIGTERM (the stop request: ignoring it would
/// leave SIGKILL as the only way to stop shipyard, which then can't stop the
/// command).
fn always_caught(signal: c_int) -> bool {
    matches!(signal, libc::SIGCHLD | libc::SIGCONT | libc::SIGTERM)
}

/// The installed handlers. Dropping it puts the previous handlers, and the
/// previous signal mask, back.
pub(crate) struct Signals {
    previous: Vec<(c_int, libc::sigaction)>,
    previous_mask: Option<libc::sigset_t>,
    /// Forwardable signals that were ignored when shipyard started.
    ignored_at_startup: Vec<c_int>,
}

// The methods below only touch statics, but take `&self` on purpose: holding a
// `Signals` proves the handlers are installed and the wake pipe exists.
#[allow(
    clippy::unused_self,
    reason = "`&self` proves the handlers are installed"
)]
impl Signals {
    /// Installs handlers for SIGCHLD (which only wakes the loop, so it can
    /// reap), SIGCONT (so the loop learns that shipyard was resumed after a
    /// stop) and every forwardable signal, then unblocks them.
    ///
    /// Catching SIGCONT doesn't change what it does: the kernel resumes a
    /// stopped process when SIGCONT is *sent*, whatever its handler.
    ///
    /// A forwardable signal that was *ignored* when shipyard started (by
    /// `nohup`, or `&` in a script) stays ignored and is never forwarded.
    /// SIGCHLD, SIGCONT and SIGTERM are always caught (see `always_caught`).
    ///
    /// The signal mask is inherited too, and a parent may have blocked
    /// signals. A blocked SIGCHLD would leave shipyard waiting forever for a
    /// command that has already exited; a blocked SIGTERM would make it
    /// unstoppable. So every caught signal is unblocked.
    pub(crate) fn install() -> Result<Self> {
        if ACTIVE.swap(true, Ordering::AcqRel) {
            return Err(Error::AlreadySupervising);
        }
        // From here on, dropping `installed` undoes whatever was done.
        let mut installed = Self {
            previous: Vec::new(),
            previous_mask: None,
            ignored_at_startup: Vec::new(),
        };
        ensure_wake_pipe()?;
        for signal in 1..=MAX_SIGNAL {
            if always_caught(signal) || is_forwardable(signal) {
                installed.catch(signal)?;
            }
        }
        installed.unblock_caught()?;
        Ok(installed)
    }

    /// Forwardable signals that were ignored when shipyard started.
    pub(crate) fn ignored_at_startup(&self) -> &[c_int] {
        &self.ignored_at_startup
    }

    fn unblock_caught(&mut self) -> Result<()> {
        let mut caught = std::mem::MaybeUninit::<libc::sigset_t>::uninit();
        let mut old = std::mem::MaybeUninit::<libc::sigset_t>::uninit();
        // SAFETY: `sigemptyset` initialises `caught`; `sigaddset` only gets
        // signal numbers `sigaction` accepted above.
        unsafe {
            libc::sigemptyset(caught.as_mut_ptr());
            for (signal, _) in &self.previous {
                libc::sigaddset(caught.as_mut_ptr(), *signal);
            }
        }
        // SAFETY: `caught` is initialised; `old` receives the current mask.
        let rc = unsafe { libc::sigprocmask(libc::SIG_UNBLOCK, caught.as_ptr(), old.as_mut_ptr()) };
        if rc == -1 {
            return Err(Error::sys("unblocking signals", Errno::last()));
        }
        // SAFETY: `sigprocmask` succeeded, so it filled in `old`.
        self.previous_mask = Some(unsafe { old.assume_init() });
        Ok(())
    }

    fn catch(&mut self, signal: c_int) -> Result<()> {
        // SAFETY: a zeroed `sigaction` is a valid "no handler" value; the
        // query below doesn't change anything.
        let mut current: libc::sigaction = unsafe { std::mem::zeroed() };
        // SAFETY: a NULL new action only reads the current one.
        if unsafe { libc::sigaction(signal, std::ptr::null(), &raw mut current) } == -1 {
            // Signals the C library keeps for itself (glibc 32–33, musl
            // 32–34) can't be queried or caught; skip them.
            return Ok(());
        }
        if current.sa_sigaction == libc::SIG_IGN && !always_caught(signal) {
            tracing::trace!(signal, "ignored at startup: left ignored, not forwarded");
            self.ignored_at_startup.push(signal);
            return Ok(());
        }

        // SAFETY: as above.
        let mut action: libc::sigaction = unsafe { std::mem::zeroed() };
        action.sa_sigaction = on_signal as *const () as libc::sighandler_t;
        // SA_RESTART: interrupted reads and writes resume instead of failing.
        // Never SA_NOCLDSTOP or SA_NOCLDWAIT: shipyard reaps its children.
        action.sa_flags = libc::SA_SIGINFO | libc::SA_RESTART;
        // SAFETY: `sa_mask` is valid storage for a signal set.
        unsafe { libc::sigemptyset(&raw mut action.sa_mask) };
        // SAFETY: `on_signal` only does async-signal-safe things.
        if unsafe { libc::sigaction(signal, &raw const action, std::ptr::null_mut()) } == -1 {
            return Err(Error::sys(
                format!("installing a handler for signal {signal}"),
                Errno::last(),
            ));
        }
        self.previous.push((signal, current));
        Ok(())
    }

    /// The descriptor that becomes readable when a signal arrives.
    pub(crate) fn wake_fd(&self) -> BorrowedFd<'static> {
        // SAFETY: the wake pipe is created before `Signals` exists and is
        // never closed, so the descriptor stays valid for the whole program.
        unsafe { BorrowedFd::borrow_raw(WAKE_READ.load(Ordering::Acquire)) }
    }

    /// Tells the handler which PID is the command, so signals it sends us
    /// can be recognised as [`Sources::COMMAND`].
    pub(crate) fn set_child(&self, pid: libc::pid_t) {
        CHILD_PID.store(pid, Ordering::Release);
    }

    /// The signals that arrived since the last call: forwardable ones, and
    /// SIGCONT.
    ///
    /// In numeric order, not arrival order: the kernel doesn't keep the order
    /// of pending standard signals either. Like standard signals, repeated
    /// deliveries of one signal (even a real-time one) count once.
    pub(crate) fn drain(&self) -> Vec<Arrival> {
        drain_flags(WAKE_READ.load(Ordering::Acquire))
    }

    /// Forgets that `signal` arrived, if it's pending.
    pub(crate) fn forget(&self, signal: c_int) {
        if let Some(flag) = usize::try_from(signal).ok().and_then(|n| PENDING.get(n)) {
            flag.store(0, Ordering::Release);
        }
    }

    /// Forgets the command: pending signals were meant for it, and its PID
    /// may be reused.
    pub(crate) fn clear_child(&self) {
        CHILD_PID.store(0, Ordering::Release);
        drop(self.drain());
    }
}

impl Drop for Signals {
    fn drop(&mut self) {
        // Restore with every signal blocked, so none arrives half-way.
        let mut all = std::mem::MaybeUninit::<libc::sigset_t>::uninit();
        let mut old = std::mem::MaybeUninit::<libc::sigset_t>::uninit();
        // SAFETY: `sigfillset` initialises `all`; `sigprocmask` fills `old`.
        unsafe {
            libc::sigfillset(all.as_mut_ptr());
            libc::sigprocmask(libc::SIG_SETMASK, all.as_ptr(), old.as_mut_ptr());
        }
        for (signal, previous) in self.previous.drain(..).rev() {
            // SAFETY: restores exactly what `sigaction` reported before.
            unsafe { libc::sigaction(signal, &raw const previous, std::ptr::null_mut()) };
        }
        let restore = match &self.previous_mask {
            Some(mask) => std::ptr::from_ref(mask),
            None => old.as_ptr(),
        };
        // SAFETY: `restore` points at a mask `sigprocmask` filled in, either
        // at install time or just above.
        unsafe { libc::sigprocmask(libc::SIG_SETMASK, restore, std::ptr::null_mut()) };
        CHILD_PID.store(0, Ordering::Release);
        ACTIVE.store(false, Ordering::Release);
    }
}

/// Empties the wake pipe *first*, then collects the flags.
///
/// The order matters: a signal arriving between the two steps has set its flag
/// before writing its wake byte. Reading flags first could consume that byte
/// while missing the flag, and the signal would wait for the next wakeup.
fn drain_flags(wake_read: RawFd) -> Vec<Arrival> {
    let mut buffer = [0u8; 64];
    loop {
        // SAFETY: `buffer` is valid for `buffer.len()` bytes.
        let n = unsafe { libc::read(wake_read, buffer.as_mut_ptr().cast(), buffer.len()) };
        if n <= 0 {
            break;
        }
    }
    (1..SLOTS)
        .filter_map(|number| {
            let sources = PENDING.get(number)?.swap(0, Ordering::Acquire);
            (sources != 0).then_some(Arrival {
                signal: c_int::try_from(number).ok()?,
                sources: Sources(sources),
            })
        })
        .collect()
}

/// Creates the non-blocking, close-on-exec wake pipe, once per process.
///
/// `pipe` then `fcntl` isn't atomic: a `fork` in another thread in between
/// could inherit the pipe. Shipyard is single-threaded, so that can't happen.
fn ensure_wake_pipe() -> Result<()> {
    if WAKE_READ.load(Ordering::Acquire) >= 0 {
        return Ok(());
    }
    let mut fds = [0 as c_int; 2];
    // SAFETY: `fds` has room for the two descriptors `pipe` returns.
    if unsafe { libc::pipe(fds.as_mut_ptr()) } == -1 {
        return Err(Error::sys("creating the signal wake pipe", Errno::last()));
    }
    let [read, write] = fds;
    for fd in [read, write] {
        // SAFETY: both descriptors were just created and are ours.
        let ok = unsafe {
            libc::fcntl(fd, libc::F_SETFD, libc::FD_CLOEXEC) != -1
                && libc::fcntl(fd, libc::F_SETFL, libc::O_NONBLOCK) != -1
        };
        if !ok {
            let errno = Errno::last();
            // SAFETY: closing the two descriptors created above, which
            // nothing else refers to yet.
            unsafe {
                libc::close(read);
                libc::close(write);
            }
            return Err(Error::sys("configuring the signal wake pipe", errno));
        }
    }
    WAKE_WRITE.store(write, Ordering::Release);
    WAKE_READ.store(read, Ordering::Release);
    Ok(())
}

/// The handler: record, wake, return. Nothing else is safe here.
extern "C" fn on_signal(signal: c_int, info: *mut libc::siginfo_t, _context: *mut libc::c_void) {
    let saved_errno = Errno::last_raw();
    // SIGCHLD only needs the wakeup: the loop reaps on every wakeup.
    if signal != libc::SIGCHLD {
        let slot = usize::try_from(signal).ok().and_then(|n| PENDING.get(n));
        if let Some(flag) = slot {
            flag.fetch_or(source_of(info).0, Ordering::Release);
        }
    }
    let wake = WAKE_WRITE.load(Ordering::Acquire);
    if wake >= 0 {
        let byte = 1u8;
        // SAFETY: `write` is async-signal-safe; a full pipe (EAGAIN) is fine,
        // since a wakeup is already pending.
        unsafe { libc::write(wake, (&raw const byte).cast(), 1) };
    }
    Errno::set_raw(saved_errno);
}

/// Where a signal came from, read from its `siginfo`.
///
/// Only Linux distinguishes kernel signals (`si_code` is positive, e.g.
/// `SI_KERNEL` for the terminal's Ctrl-C) from ones a process sent (`si_code`
/// zero or negative: `kill`, `sigqueue`, `tkill`). A sender in an ancestor
/// PID namespace shows up with `si_pid` 0; it's still [`Sources::OTHER`].
///
/// macOS reports `si_code` 0 for everything, and gives a terminal signal the
/// PID of whoever wrote to the terminal. It also keeps one `siginfo` per
/// process, so with two signals pending at once the sender of one can be
/// reported for the other. So there, only "sent by the command" is
/// recognised, and that only on a best-effort basis.
fn source_of(info: *const libc::siginfo_t) -> Sources {
    if info.is_null() {
        return Sources::OTHER;
    }
    // SAFETY: the kernel passes a valid `siginfo_t` to SA_SIGINFO handlers.
    let code = unsafe { (*info).si_code };
    if cfg!(target_os = "linux") && code > 0 {
        return Sources::KERNEL;
    }
    // SAFETY: as above; `si_pid` is set for signals a process sent.
    let sender = unsafe { (*info).si_pid() };
    if sender != 0 && sender == CHILD_PID.load(Ordering::Acquire) {
        Sources::COMMAND
    } else {
        Sources::OTHER
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_forwarding_table() {
        for signal in [
            libc::SIGINT,
            libc::SIGTERM,
            libc::SIGHUP,
            libc::SIGQUIT,
            libc::SIGUSR1,
            libc::SIGUSR2,
            libc::SIGWINCH,
        ] {
            assert!(is_forwardable(signal), "{signal} should be forwarded");
        }
        for signal in [
            libc::SIGCHLD,
            libc::SIGKILL,
            libc::SIGSTOP,
            libc::SIGSEGV,
            libc::SIGPIPE,
            libc::SIGTSTP,
            libc::SIGCONT,
            libc::SIGTTIN,
        ] {
            assert!(!is_forwardable(signal), "{signal} should not be forwarded");
        }
        assert!(!is_forwardable(0));
        assert!(!is_forwardable(MAX_SIGNAL + 1));
    }

    #[cfg(target_os = "linux")]
    #[test]
    fn linux_realtime_signals_are_forwarded() {
        assert!(is_forwardable(34));
        assert!(is_forwardable(64));
    }

    #[test]
    fn a_flag_set_after_the_pipe_was_read_is_still_collected() {
        // A pipe with nothing in it, as if the wake byte was already consumed.
        let mut fds = [0 as c_int; 2];
        // SAFETY: `fds` has room for two descriptors.
        assert_eq!(unsafe { libc::pipe(fds.as_mut_ptr()) }, 0);
        let [read, write] = fds;
        // SAFETY: `read` was just created.
        unsafe { libc::fcntl(read, libc::F_SETFL, libc::O_NONBLOCK) };

        let usr2 = PENDING
            .get(usize::try_from(libc::SIGUSR2).unwrap())
            .unwrap();
        usr2.fetch_or(Sources::OTHER.0, Ordering::Release);
        usr2.fetch_or(Sources::COMMAND.0, Ordering::Release);
        let drained = drain_flags(read);
        let arrival = drained.iter().find(|a| a.signal == libc::SIGUSR2);
        assert_eq!(
            arrival.map(|a| a.sources),
            Some(Sources::OTHER.union(Sources::COMMAND)),
            "{drained:?}"
        );
        assert!(
            !drain_flags(read).iter().any(|a| a.signal == libc::SIGUSR2),
            "flags are cleared"
        );

        // SAFETY: closing descriptors this test created.
        unsafe {
            libc::close(read);
            libc::close(write);
        }
    }
}
