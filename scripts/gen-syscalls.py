#!/usr/bin/env python3
"""Generates crates/shipyard-runtime/src/security/syscalls.rs: the system
calls of each architecture Shipyard builds for, by name and number (stage 4,
seccomp: profiles name system calls, and the filter needs their numbers).

Two sources:

- the libc crate's `SYS_*` constants, glibc's and musl's together (each lacks
  a few the other has; where both have a name, the numbers must agree), and
  the names alone on every other Linux architecture it knows: a profile
  written for several architectures names calls this one doesn't have
  (`arm_fadvise64_64`), which are skipped, where a name no architecture has
  is a mistake;
- the system calls added since Linux 5.1, which have the same number on every
  architecture (424 and up, the kernel's `scripts/syscall.tbl`), for the ones
  the libc crate doesn't have yet: a filter can only allow a call it can name,
  and a program refused one (glibc's `fchmodat` uses `fchmodat2`) breaks.

Run it after updating the libc crate, or when the kernel adds system calls
(add them to UNIFIED, from scripts/syscall.tbl, or to EXTRA for one
architecture's own):

    scripts/gen-syscalls.py
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates/shipyard-runtime/src/security/syscalls.rs"

# Where libc declares each architecture's numbers.
SOURCES = {
    "aarch64": ["linux/gnu/b64/aarch64/mod.rs", "linux/musl/b64/aarch64/mod.rs"],
    "x86_64": ["linux/gnu/b64/x86_64/not_x32.rs", "linux/musl/b64/x86_64/mod.rs"],
}

# Linux's `scripts/syscall.tbl`, the "common" entries from 449 (the libc crate
# has the older unified ones). Both tables were checked entry by entry against
# Linux 7.3's (`scripts/syscall.tbl` and `arch/x86/entry/syscalls/syscall_64.tbl`).
UNIFIED = {
    "futex_waitv": 449,
    "set_mempolicy_home_node": 450,
    "cachestat": 451,
    "fchmodat2": 452,
    "map_shadow_stack": 453,
    "futex_wake": 454,
    "futex_wait": 455,
    "futex_requeue": 456,
    "statmount": 457,
    "listmount": 458,
    "lsm_get_self_attr": 459,
    "lsm_set_self_attr": 460,
    "lsm_list_modules": 461,
    "mseal": 462,
    "setxattrat": 463,
    "getxattrat": 464,
    "listxattrat": 465,
    "removexattrat": 466,
    "open_tree_attr": 467,
    "file_getattr": 468,
    "file_setattr": 469,
    "listns": 470,
    "rseq_slice_yield": 471,
    "fchroot": 472,
}

# Calls of one architecture the libc crate lacks, from its kernel table.
EXTRA = {
    "aarch64": {},
    "x86_64": {
        # Removed long ago, but still numbered (and named by old profiles).
        "create_module": 174,
        "get_kernel_syms": 177,
        "query_module": 178,
        "uretprobe": 335,
        "uprobe": 336,
    },
}

# Names of other architectures' private calls, which libc has no constants for
# (32-bit Arm's `__ARM_NR_*`, RISC-V's): only for "is this a real name?".
OTHER_NAMES = {
    "breakpoint",
    "cacheflush",
    "get_tls",
    "riscv_flush_icache",
    "riscv_hwprobe",
    "set_tls",
    "usr26",
    "usr32",
}


def libc_dir() -> Path:
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1"], cwd=ROOT))
    for package in meta["packages"]:
        if package["name"] == "libc":
            return Path(package["manifest_path"]).parent
    sys.exit("the libc crate isn't in the dependency graph")


def numbers(path: Path) -> dict[str, int]:
    found = re.findall(r"pub const SYS_(\w+)\s*:\s*c_long\s*=\s*(\d+)\s*;", path.read_text())
    return {name: int(value) for name, value in found}


def table(arch: str, base: Path) -> dict[str, int]:
    merged: dict[str, int] = {}
    for source in SOURCES[arch]:
        for name, value in numbers(base / source).items():
            if merged.setdefault(name, value) != value:
                sys.exit(f"{arch}: glibc and musl disagree on {name}")
    for name, value in [*UNIFIED.items(), *EXTRA[arch].items()]:
        if merged.setdefault(name, value) != value:
            sys.exit(f"{arch}: libc has {name} as {merged[name]}, the kernel as {value}")
    return merged


def every_name(base: Path) -> set[str]:
    """Every system call name the libc crate knows, on any Linux architecture."""
    names: set[str] = set()
    for source in (base / "linux").rglob("*.rs"):
        names.update(numbers(source))
    return names


def main() -> None:
    base = libc_dir() / "src/unix/linux_like"
    out = [
        "//! The system calls of the architectures Shipyard builds for, by name",
        "//! and number (for seccomp profiles, which name them), and every name",
        "//! any Linux architecture has. Generated by `scripts/gen-syscalls.py`",
        "//! from the libc crate (glibc's and musl's numbers) and the kernel's",
        "//! unified numbers for newer calls: don't edit by hand.",
        "",
    ]
    known = every_name(base) | set(UNIFIED) | OTHER_NAMES
    for arch in SOURCES:
        calls = table(arch, base)
        if len(set(calls.values())) != len(calls):
            sys.exit(f"{arch}: two names share a number")
        known |= set(calls)
        out.append(f"/// `{arch}`: {len(calls)} system calls, sorted by name.")
        out.append(f"pub(super) const {arch.upper()}: &[(&str, u32)] = &[")
        out += [f'    ("{name}", {calls[name]}),' for name in sorted(calls)]
        out.append("];")
        out.append("")
    out.append(f"/// Every system call name of any Linux architecture: {len(known)}, sorted.")
    out.append("pub(super) const ANY_ARCHITECTURE: &[&str] = &[")
    out += [f'    "{name}",' for name in sorted(known)]
    out.append("];")
    out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
